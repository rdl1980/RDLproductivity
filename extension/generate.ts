import { scraperSourceWith } from "../src/lib/kdp-bookmarklet";
import { salesCollectorSourceWith } from "../src/lib/kdp-sales-collector";

/**
 * The scripts the extension injects into the KDP pages: the bookmarklets'
 * code with hooks that report to the background instead of navigating. A
 * heartbeat keeps the service worker alive while the page is read.
 */

const wrap = (step: string, body: string) =>
  `// Generated by \`pnpm extension:build\` from src/lib; do not edit.
(() => {
  const api = globalThis.browser ?? globalThis.chrome;
  const send = (message) => api.runtime.sendMessage({ step: ${JSON.stringify(step)}, ...message }).catch(() => {});
  const heartbeat = setInterval(() => send({ type: "progress" }), 5000);
  const finish = (message) => { clearInterval(heartbeat); send(message); };
  ${body}
})();
`;

export function generatedScripts(): Record<string, string> {
  return {
    "books.js": wrap(
      "books",
      scraperSourceWith({
        deliver: '(hash) => finish({ type: "result", hash })',
        fail: '(message) => finish({ type: "result", error: message })',
        // The background opened the page itself.
        onPage: "true",
      }),
    ),
    "sales.js": wrap(
      "sales",
      salesCollectorSourceWith({
        deliver: '(hash) => finish({ type: "result", hash })',
        fail: '(message) => finish({ type: "result", error: message })',
        progress: '(text) => send({ type: "progress", text })',
        onPage: "true",
      }),
    ),
  };
}
